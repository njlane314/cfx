#include <bits/stdc++.h>

using namespace std;

using ll = long long;

void solve(istream& in = cin, ostream& out = cout) {
    int w;
    in >> w;

    out << (w > 2 && w % 2 == 0 ? "YES" : "NO") << '\n';
}

int main() {
    ios::sync_with_stdio(false);
    cin.tie(nullptr);

    solve();
    return 0;
}
